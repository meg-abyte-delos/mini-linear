-- Area 7 inbox (spec: area7-inbox-interface-spec v1). Run as OWNER after 0005. Two tenant tables (subscriptions live in issue_subscribers, 0103) with FORCE RLS:
-- the usual workspace tenant_isolation policy plus a RESTRICTIVE per-user policy (app.user_id), so a row is visible
-- only to its recipient inside its workspace. Admins never read another user's inbox.
BEGIN;
CREATE TYPE notification_type AS ENUM ('assigned','mention','comment','status_change','due_soon');

CREATE TABLE notifications (
  id uuid PRIMARY KEY, -- uuidv7, generated by the app: list order is id desc
  workspace_id uuid NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE, -- recipient
  actor_id uuid REFERENCES users(id) ON DELETE SET NULL,
  type notification_type NOT NULL,
  issue_id uuid NOT NULL, comment_id uuid,
  read_at timestamptz, archived_at timestamptz, snoozed_until timestamptz, -- snooze cap (+1 year, else 422) is enforced by the API
  created_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (issue_id, workspace_id) REFERENCES issues(id, workspace_id) ON DELETE CASCADE,
  FOREIGN KEY (comment_id, workspace_id) REFERENCES comments(id, workspace_id) ON DELETE CASCADE);
CREATE INDEX notifications_inbox_idx ON notifications (workspace_id, user_id, id DESC) WHERE archived_at IS NULL;
CREATE INDEX notifications_unread_idx ON notifications (workspace_id, user_id) WHERE archived_at IS NULL AND read_at IS NULL;
-- One mention notification per (recipient, issue, comment): a comment edit notifies only newly mentioned users.
CREATE UNIQUE INDEX notifications_mention_uq ON notifications (user_id, issue_id, comment_id) WHERE type = 'mention';

CREATE TABLE notification_preferences (
  workspace_id uuid NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  type notification_type NOT NULL, in_app boolean NOT NULL DEFAULT true, email boolean NOT NULL DEFAULT false,
  PRIMARY KEY (workspace_id, user_id, type));

DO $$ DECLARE t text; BEGIN
  FOREACH t IN ARRAY ARRAY['notifications','notification_preferences'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format($p$CREATE POLICY tenant_isolation ON %I
      USING (workspace_id = nullif(current_setting('app.workspace_id', true), '')::uuid)
      WITH CHECK (workspace_id = nullif(current_setting('app.workspace_id', true), '')::uuid)$p$, t);
  END LOOP;
END $$;
-- Per-user: restrictive policies AND with tenant_isolation. Unset app.user_id => zero rows.
CREATE POLICY recipient_only ON notifications AS RESTRICTIVE
  USING (user_id = nullif(current_setting('app.user_id', true), '')::uuid)
  WITH CHECK (user_id = nullif(current_setting('app.user_id', true), '')::uuid);
CREATE POLICY own_prefs ON notification_preferences AS RESTRICTIVE
  USING (user_id = nullif(current_setting('app.user_id', true), '')::uuid)
  WITH CHECK (user_id = nullif(current_setting('app.user_id', true), '')::uuid);

GRANT SELECT, INSERT, UPDATE, DELETE ON notifications TO app_user;
GRANT SELECT, INSERT, UPDATE ON notification_preferences TO app_user;

-- Fan-out. The single SECURITY DEFINER of this area: it inserts a notification for ANOTHER user, which the recipient
-- policy forbids to app_user. Tenant comes from app.workspace_id and actor from app.user_id (never from arguments).
-- It checks: recipient is not the actor, is a member who can see the issue (admin+ all, member by team, guest by an
-- active share, issue not deleted), and has in_app enabled for the type. Returns true when a row was inserted.
CREATE FUNCTION notify(p_id uuid, p_recipient uuid, p_type notification_type, p_issue uuid, p_comment uuid)
RETURNS boolean LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, public AS $$
DECLARE ws uuid := nullif(current_setting('app.workspace_id', true), '')::uuid;
        actor uuid := nullif(current_setting('app.user_id', true), '')::uuid;
        r public.workspace_role; i public.issues%ROWTYPE; ok boolean; n int;
BEGIN
  IF ws IS NULL OR actor IS NULL OR p_recipient = actor THEN RETURN false; END IF;
  SELECT role INTO r FROM public.memberships WHERE workspace_id = ws AND user_id = p_recipient;
  IF r IS NULL THEN RETURN false; END IF;
  SELECT * INTO i FROM public.issues WHERE id = p_issue AND workspace_id = ws AND deleted_at IS NULL;
  IF NOT FOUND THEN RETURN false; END IF;
  IF r IN ('owner','admin') THEN ok := true;
  ELSIF r = 'guest' THEN
    ok := EXISTS (SELECT 1 FROM public.issue_shares s WHERE s.workspace_id = ws AND s.issue_id = p_issue AND s.guest_user_id = p_recipient AND s.revoked_at IS NULL);
  ELSE ok := EXISTS (SELECT 1 FROM public.team_memberships tm WHERE tm.workspace_id = ws AND tm.team_id = i.team_id AND tm.user_id = p_recipient);
  END IF;
  IF NOT ok THEN RETURN false; END IF;
  IF EXISTS (SELECT 1 FROM public.notification_preferences p WHERE p.workspace_id = ws AND p.user_id = p_recipient AND p.type = p_type AND NOT p.in_app) THEN RETURN false; END IF;
  INSERT INTO public.notifications (id, workspace_id, user_id, actor_id, type, issue_id, comment_id)
    VALUES (p_id, ws, p_recipient, actor, p_type, p_issue, p_comment) ON CONFLICT DO NOTHING;
  GET DIAGNOSTICS n = ROW_COUNT;
  RETURN n = 1;
END $$;
GRANT SELECT ON issues, team_memberships, issue_shares, notification_preferences TO definer;
GRANT INSERT ON notifications TO definer;
GRANT USAGE, CREATE ON SCHEMA public TO definer;
ALTER FUNCTION notify(uuid, uuid, notification_type, uuid, uuid) OWNER TO definer;
REVOKE CREATE ON SCHEMA public FROM definer;
REVOKE ALL ON FUNCTION notify(uuid, uuid, notification_type, uuid, uuid) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION notify(uuid, uuid, notification_type, uuid, uuid) TO app_user;
COMMIT;
